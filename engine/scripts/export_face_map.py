"""Write the face map the web draws the spot diary on (web/src/data/faceMap.ts): the canonical
face's outline, eyes, brows, lips and nose, and each zone as polygons, all in the same canonical
millimetres as candidate features face_x_mm / face_y_mm (x < 0 is the subject's right, y up).

Zones come from app.facemap.zone_of, sampled every 0.5 mm inside the outline, so the drawing
and the zone a mark is given always agree.

Usage (from engine/):
  uv run python -m scripts.export_face_map ../web/src/data/faceMap.ts
"""

import json
import sys

import cv2
import numpy as np

from app import facemap
from app.landmarks import FACE_OVAL

STEP_MM = 0.5
FEATURES = {
    "right_eye": [33, 7, 163, 144, 145, 153, 154, 155, 133, 173, 157, 158, 159, 160, 161, 246],
    "left_eye": [263, 249, 390, 373, 374, 380, 381, 382, 362, 398, 384, 385, 386, 387, 388, 466],
    "right_brow": [70, 63, 105, 66, 107, 55, 65, 52, 53, 46],
    "left_brow": [300, 293, 334, 296, 336, 285, 295, 282, 283, 276],
    "lips": [
        61,
        146,
        91,
        181,
        84,
        17,
        314,
        405,
        321,
        375,
        291,
        409,
        270,
        269,
        267,
        0,
        37,
        39,
        40,
        185,
    ],
    "nose_bridge": [168, 6, 197, 195, 5, 4],
    "nose_base": [64, 98, 97, 2, 326, 327, 294],
}
OPEN = {"nose_bridge", "nose_base"}  # drawn as lines, not closed shapes


def _pts(v: np.ndarray, idx: list[int]) -> list[list[float]]:
    return [[round(float(v[i, 0]), 1), round(float(v[i, 1]), 1)] for i in idx]


def build() -> dict:
    mesh = facemap.canonical()
    if mesh is None:
        raise SystemExit("face model missing: download face_landmarker.task (see README)")
    v = mesh[0]
    outline = np.array(_pts(v, FACE_OVAL), np.float32)
    x0, y0 = outline.min(axis=0) - 1
    x1, y1 = outline.max(axis=0) + 1
    xs = np.arange(x0, x1, STEP_MM)
    ys = np.arange(y0, y1, STEP_MM)
    inside = np.zeros((len(ys), len(xs)), np.uint8)
    cv2.fillPoly(inside, [np.round((outline - [x0, y0]) / STEP_MM).astype(np.int32)], 1)
    labels = np.full(inside.shape, -1, np.int16)
    for r, y in enumerate(ys):
        for c, x in enumerate(xs):
            if inside[r, c]:
                labels[r, c] = facemap.ZONES.index(facemap.zone_of(float(x), float(y)))
    zones = {}
    for k, name in enumerate(facemap.ZONES):
        mask = (labels == k).astype(np.uint8)
        contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        polys = []
        for cnt in contours:
            if cv2.contourArea(cnt) < 4:
                continue
            cnt = cv2.approxPolyDP(cnt, 1.5, True).reshape(-1, 2)
            polys.append(
                [[round(x0 + p[0] * STEP_MM, 1), round(y0 + p[1] * STEP_MM, 1)] for p in cnt]
            )
        zones[name] = polys
    return {
        "bounds": {
            "min_x": round(float(x0), 1),
            "max_x": round(float(x1), 1),
            "min_y": round(float(y0), 1),
            "max_y": round(float(y1), 1),
        },
        "outline": _pts(v, FACE_OVAL),
        "features": {
            n: {"points": _pts(v, idx), "closed": n not in OPEN} for n, idx in FEATURES.items()
        },
        "zones": zones,
    }


def main() -> None:
    out = sys.argv[1] if len(sys.argv) > 1 else "../web/src/data/faceMap.ts"
    data = build()
    with open(out, "w") as f:
        f.write(
            "/** Canonical face for the spot diary, generated by engine/scripts/export_face_map.py:\n"
            " * do not edit. Millimetres, x < 0 is the subject's right, y up (flip y for SVG). Zone\n"
            " * shapes match the zone the engine gives a mark (app/facemap.py zone_of). */\n"
            "export type Pt = [number, number]\n"
            "export const FACE_MAP: {\n"
            "  bounds: { min_x: number; max_x: number; min_y: number; max_y: number }\n"
            "  outline: Pt[]\n"
            "  features: Record<string, { points: Pt[]; closed: boolean }>\n"
            "  zones: Record<string, Pt[][]>\n"
            "} = " + json.dumps(data, separators=(",", ":")) + "\n"
        )
    print(f"wrote {out}: {sum(len(p) for p in data['zones'].values())} zone shapes")


if __name__ == "__main__":
    main()
